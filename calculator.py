"""A small calculator used to practice the Git collaboration workflow."""


def add(a, b):
    return a + b


def subtract(a, b):
    return a - b


def divide(a, b):
    return a / b


if __name__ == "__main__":
    print("2 + 3 =", add(2, 3))
    print("5 - 3 =", subtract(5, 3))
    print("6 / 2 =", divide(6, 2))
